/**
 * Build vendor/: the MathJax code and fonts the renderer uses, without the
 * rest of the @mathjax packages (other output formats, ESM copies, sources,
 * speech rules, menus).
 *
 *   vendor/mathjax.cjs        src/math/mathjax-lib.cjs and everything it requires, minified
 *   vendor/newcm-dynamic/*.cjs on-demand font data, rewritten to use the bundle's font class
 *   vendor/LICENSE            MathJax's Apache-2.0 license
 *
 * Run by `npm run build` (also before tests). vendor/ is committed, so installs
 * from git (`npm install --omit=dev`, no build step) work; rebuild and commit
 * it after upgrading MathJax. The output is deterministic.
 */
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = join(root, "vendor");
const require = createRequire(join(root, "package.json"));

rmSync(vendor, { recursive: true, force: true });
mkdirSync(join(vendor, "newcm-dynamic"), { recursive: true });

const result = await build({
	entryPoints: [join(root, "src/math/mathjax-lib.cjs")],
	outfile: join(vendor, "mathjax.cjs"),
	bundle: true,
	platform: "node",
	format: "cjs",
	target: "node20",
	minify: true,
	legalComments: "none",
	define: { __MATHJAX_BUNDLED__: "true" },
	metafile: true,
	logLevel: "warning",
});

// Nothing the renderer never runs may sneak in through a stray require.
const inputs = Object.keys(result.metafile.inputs);
const unwanted = inputs.filter((file) => /speech-rule-engine|mj-context-menu|[\\/]a11y[\\/]|[\\/]chtml[\\/.]/.test(file));
if (unwanted.length > 0) throw new Error(`unexpected modules in the MathJax bundle:\n${unwanted.join("\n")}`);

// On-demand font files require the font class and Direction; point them at the bundle's instances.
const fontDir = join(dirname(require.resolve("@mathjax/mathjax-newcm-font/js/svg.js")), "svg", "dynamic");
const SHARED = {
	"../../svg.js": 'require("../mathjax.cjs").shared.newcmSvg',
	"@mathjax/src/cjs/output/common/Direction.js": 'require("../mathjax.cjs").shared.direction',
};
let dynamicBytes = 0;
const files = readdirSync(fontDir).filter((f) => f.endsWith(".js"));
for (const file of files) {
	let code = readFileSync(join(fontDir, file), "utf8");
	code = code.replace(/require\("([^"]+)"\)/g, (match, spec) => {
		if (!(spec in SHARED)) throw new Error(`${file}: unexpected require("${spec}")`);
		return SHARED[spec];
	});
	const { code: min } = await transform(code, { loader: "js", format: "cjs", minify: true, legalComments: "none" });
	// .cjs: the package is "type": "module", so a .js file would load as ESM.
	writeFileSync(join(vendor, "newcm-dynamic", file.replace(/\.js$/, ".cjs")), min);
	dynamicBytes += min.length;
}

copyFileSync(require.resolve("@mathjax/src/LICENSE"), join(vendor, "LICENSE"));
const version = JSON.parse(readFileSync(require.resolve("@mathjax/src/package.json"), "utf8")).version;
writeFileSync(
	join(vendor, "README.md"),
	`Generated by tools/bundle-mathjax.mjs from MathJax ${version} (Apache-2.0, see LICENSE). Do not edit.\n`,
);

const mb = (n) => `${(n / 1024 / 1024).toFixed(2)} MB`;
const bundleBytes = readFileSync(join(vendor, "mathjax.cjs")).length;
console.log(`vendor/mathjax.cjs ${mb(bundleBytes)} (${inputs.length} modules), newcm-dynamic ${mb(dynamicBytes)} (${files.length} files)`);
